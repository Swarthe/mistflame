// @ts-check
//
// Convert legacy rows that hold raw HTML in email.body into the split
// body / body_html form.
//
// Before body_html existed, the email receiver stored `parsed.text ?? parsed.html`,
// so any message sent without a text/plain alternative left markup in body, which
// the thread view then rendered as escaped text. This turns those rows into a
// readable plain-text body plus the HTML fragment.
//
// Usage (see CLAUDE.md for the full procedure, including the backup):
//
//   npx wrangler d1 execute DB --local --json --command \
//     "SELECT id, body FROM email WHERE body_html IS NULL AND sender IS NULL \
//      AND trim(body, ' '||char(9)||char(10)||char(13)) LIKE '<%'" > dump.json
//   node scripts/backfill-html-bodies.mjs dump.json > db/migrations/002-backfill-html.sql
//   # review the SQL, then
//   npx wrangler d1 execute DB --local --file db/migrations/002-backfill-html.sql
//
// SQLite's one-argument trim() strips spaces only, so the character set above
// is needed, or a body starting with a newline is silently left out.
//
// Afterwards, rerun the SELECT to confirm it returns nothing. The apply step is
// the easiest part of this to skip by accident, and there is no other signal:
// unconverted rows simply keep rendering as visible markup.
//
// Only inbound rows (sender IS NULL) are candidates: outbound bodies were always
// composed as plain text by this app, so they cannot contain a stored HTML body.
//
// The generated UPDATEs carry `AND body_html IS NULL`, so applying the file twice
// is a no-op rather than a double conversion.

import { readFileSync } from 'node:fs';
import { htmlToText, htmlToFragment } from '../src/lib/html-to-text.mjs';

/** A body must open with a tag and carry real markup, not just a stray "<". */
const OPENS_WITH_TAG = /^<(?:!doctype\s+html|\?xml|!--|html|head|body|div|table|tbody|tr|td|p|span|font|center|ul|ol|h[1-6]|a|img|b|strong|meta|style)\b/i;
const HAS_MARKUP = /<\/[a-z]+\s*>|<br\s*\/?>|<img\b|<meta\b/i;

/** @param {string} value */
function sqlString(value) {
    // SQLite string literals escape a single quote by doubling it. NUL cannot
    // appear in a literal at all, and has no business in an email body.
    return `'${value.replace(/\0/g, '').replace(/'/g, "''")}'`;
}

/** @param {string} body */
function looksLikeHtml(body) {
    const trimmed = body.trim();
    return OPENS_WITH_TAG.test(trimmed) && HAS_MARKUP.test(trimmed);
}

/**
 * wrangler --json emits [{ results: [...], success, meta }]; a hand-made file
 * may be a bare array of rows or a single object with results.
 * @param {unknown} parsed
 * @returns {{ id: number, body: string | null }[]}
 */
function extractRows(parsed) {
    if (Array.isArray(parsed)) {
        if (parsed.length > 0 && parsed[0] !== null && typeof parsed[0] === 'object'
            && 'results' in parsed[0]) {
            return parsed.flatMap(entry => entry.results ?? []);
        }
        return /** @type {{ id: number, body: string | null }[]} */ (parsed);
    }
    if (parsed !== null && typeof parsed === 'object' && 'results' in parsed) {
        const single = /** @type {{ results?: { id: number, body: string | null }[] }} */ (parsed);
        return single.results ?? [];
    }
    throw new Error('Unrecognised dump format: expected an array or { results }.');
}

const path = process.argv[2];
if (!path) {
    console.error('usage: node scripts/backfill-html-bodies.mjs <dump.json>');
    process.exit(2);
}

const rows = extractRows(JSON.parse(readFileSync(path, 'utf8')));

/** @type {string[]} */
const statements = [];
/** @type {{ id: number, reason: string }[]} */
const skipped = [];

for (const row of rows) {
    const id = Number(row.id);
    if (!Number.isInteger(id)) {
        skipped.push({ id: NaN, reason: 'row has no usable id' });
        continue;
    }
    const body = row.body;
    if (typeof body !== 'string' || !body.trim()) {
        skipped.push({ id, reason: 'body empty' });
        continue;
    }
    if (!looksLikeHtml(body)) {
        skipped.push({ id, reason: 'does not look like HTML' });
        continue;
    }

    const fragment = htmlToFragment(body);
    if (!fragment) {
        skipped.push({ id, reason: 'no HTML left after stripping the wrapper' });
        continue;
    }

    const text = htmlToText(body);
    if (!text.trim()) {
        // Replacing a body with an empty string would lose the row's only
        // readable content, so leave it exactly as it is.
        skipped.push({ id, reason: 'HTML yielded no text' });
        continue;
    }

    statements.push(
        `UPDATE email SET body_html = ${sqlString(fragment)}, `
        + `body = ${sqlString(text)} WHERE id = ${id} AND body_html IS NULL;`);
}

const out = [
    '-- Generated by scripts/backfill-html-bodies.mjs. Do not edit by hand.',
    `-- Source dump: ${path}`,
    `-- Rows in dump ${rows.length}, converted ${statements.length},`
    + ` skipped ${skipped.length}`,
    '--',
    '-- Contains real correspondence, so this file is gitignored.',
    '',
    ...statements,
    '',
];
process.stdout.write(out.join('\n'));

// The summary goes to stderr so stdout stays pure SQL, but every line is also a
// valid SQL comment and free of semicolons. Merging stderr into the output file
// by accident (`> out.sql 2>&1`) is easy to do, and would otherwise leave a
// fragment such as `converted: 40` for wrangler to hand SQLite as a statement,
// failing the whole file with a syntax error near "rows".
console.error(`-- rows in dump  ${rows.length}`);
console.error(`-- converted     ${statements.length}`);
console.error(`-- skipped       ${skipped.length}`);
for (const entry of skipped) {
    console.error(`--   id ${entry.id}: ${entry.reason}`);
}
if (statements.length === 0) {
    console.error('-- nothing to apply');
}
